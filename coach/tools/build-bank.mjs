// Compiles data/*.txt (word|kannada|meaning|example) into js/bank.js so the app works fully offline.
// Order: track files in numeric order (daily1, daily2, …), which is also the learning order.
import fs from "fs"; import path from "path";
const dir = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "data");
const files = fs.readdirSync(dir).filter((f) => /^[a-z]+\d+\.txt$/.test(f))
  .sort((a, b) => a.replace(/\d+/, "").localeCompare(b.replace(/\d+/, "")) || +a.match(/\d+/)[0] - +b.match(/\d+/)[0]);
const words = [], seen = new Set();
for (const f of files) {
  const t = f.replace(/\d+\.txt$/, ""), lvl = +f.match(/\d+/)[0];
  for (const line of fs.readFileSync(path.join(dir, f), "utf8").split("\n")) {
    if (!line.trim() || line.startsWith("#")) continue;
    const [w, k, m, s] = line.split("|").map((x) => x.trim());
    if (!w || !k || seen.has(t + ":" + w.toLowerCase())) continue; seen.add(t + ":" + w.toLowerCase());
    words.push([w, k, m, s, t, lvl]);
  }
}
const phrases = fs.readFileSync(path.join(dir, "phrases.txt"), "utf8").split("\n").filter((l) => l.trim() && !l.startsWith("#")).map((l) => l.split("|").map((x) => x.trim()));
fs.writeFileSync(path.join(dir, "..", "js", "bank.js"),
  "// GENERATED by tools/build-bank.mjs from data/*.txt. Do not edit by hand.\n" +
  "export const BANK = " + JSON.stringify(words) + ";\nexport const PHRASES2 = " + JSON.stringify(phrases) + ";\n");
console.log(`bank: ${words.length} words from ${files.length} files, ${phrases.length} phrases`);

// ---- short stories: data/stories.txt -> js/stories.js
const stories = []; let cur = null;
for (const raw of fs.readFileSync(path.join(dir, "stories.txt"), "utf8").split("\n")) {
  const line = raw.trim(); if (!line || (line.startsWith("#") && !line.startsWith("##"))) continue;
  if (line.startsWith("## ")) { const [id, genre, icon, title, kn] = line.slice(3).split("|").map((x) => x.trim()); stories.push(cur = { id, genre, icon, title, kn, lines: [], quiz: [] }); continue; }
  if (line.startsWith("? ")) { cur.quiz.push(line.slice(2).split("|").map((x) => x.trim())); continue; }
  const [en, k] = line.split("|").map((x) => x.trim()); if (en && k) cur.lines.push([en, k]); else throw new Error("bad story line: " + line);
}
for (const s of stories) if (s.quiz.some((q) => q.length !== 4) || s.lines.length < 8) throw new Error("check story " + s.id);
const gloss = {}; for (const l of fs.readFileSync(path.join(dir, "storywords.txt"), "utf8").split("\n")) { if (!l.trim() || l.startsWith("#")) continue; const [w, k, m] = l.split("|").map((x) => x.trim()); if (w && k) gloss[w.toLowerCase()] = [k, m || ""]; }
fs.writeFileSync(path.join(dir, "..", "js", "stories.js"), "// GENERATED by tools/build-bank.mjs from data/stories.txt + storywords.txt. Do not edit by hand.\nexport const STORIES = " + JSON.stringify(stories) + ";\nexport const GLOSS = " + JSON.stringify(gloss) + ";\n");
console.log(`stories: ${stories.length}, ${stories.reduce((a, s) => a + s.lines.length, 0)} lines, ${stories.reduce((a, s) => a + s.lines.reduce((b, l) => b + l[0].split(/\s+/).length, 0), 0)} words`);
